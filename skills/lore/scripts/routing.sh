#!/usr/bin/env bash
# Build the lore routing file from each scope repo's readme frontmatter.
# Prints it, or writes <root>/readme.md with --write. The root defaults to ~/lore.
set -euo pipefail

root="$HOME/lore" write=no
while [[ $# -gt 0 ]]; do
	case $1 in
	--root) root=${2%/}; shift 2 ;;
	--write) write=yes; shift ;;
	*) echo "usage: routing.sh [--root <dir>] [--write]" >&2; exit 2 ;;
	esac
done

field() { awk -v key="$2" 'NR == 1 && $0 != "---" { exit } NR > 1 && $0 == "---" { exit } index($0, key ": ") == 1 { print substr($0, length(key) + 3); exit }' "$1"; }

build() {
	cat <<'HEAD'
# Lore

Private knowledge for the agents on this machine: who the user is, how they work, and what they
know about each project. Read this first, then the readme of the scope repo you work in.

Each folder is its own private git repo, holding `projects/`, `skills/` and optionally `repos/`
and `agents.md`.

## Scopes on this machine

HEAD
	local found=no readme name
	for readme in "$root"/*/readme.md; do
		[[ -f $readme ]] || continue
		name=$(basename "$(dirname "$readme")")
		found=yes
		printf -- '- **`%s/`**: %s\n' "$name" "$(field "$readme" scope)"
		printf '  - Cloned on: %s\n' "$(field "$readme" machines)"
		printf '  - Writes here: %s\n' "$(field "$readme" writes)"
		if [[ -f $root/$name/agents.md ]]; then
			printf '  - Read in every session: [%s/agents.md](%s/agents.md)\n' "$name" "$name"
		fi
	done
	[[ $found == yes ]] || printf -- '- None yet.\n'
	cat <<'TAIL'

## Where writes go

- Into the scope whose "Writes here" fits. Read that repo's readme before writing.
- Unsure: the narrower scope. Moving content toward a broader scope can leak for good, while the
  reverse is safe to fix later.
- After writing, commit and push that repo.

## Code repos

Steering for contributing to a code repo that can't be checked into it sits in its scope's repo
at `repos/<code-repo>/`, with an upstream page `repos/<code-repo>.md` (its remote URL and local
path). Plans for it sit in a project under `projects/`. Lore is the only source: a checkout's
generated copy of its notes is never edited directly.

This file is generated by the lore skill's `routing.sh`; edit the scope readmes instead.
TAIL
}

if [[ $write == yes ]]; then build >"$root/readme.md"; else build; fi

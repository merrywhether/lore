#!/usr/bin/env bash
# Build the lore routing file from each scope repo's readme frontmatter.
# Prints it, or writes <root>/readme.md with --write. The root defaults to ~/lore.
# Every folder in the root is a scope. One without a usable readme.md (missing, named in
# another case, or lacking a field) is left out with a warning, and --write writes nothing
# until every scope is usable, so a working routing file is never replaced by a worse one.
set -euo pipefail

scripts=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=frontmatter.sh
source "$scripts/frontmatter.sh"

root="$HOME/lore" write=no
while [[ $# -gt 0 ]]; do
	case $1 in
	--root) root=${2%/}; shift 2 ;;
	--write) write=yes; shift ;;
	*) echo "usage: routing.sh [--root <dir>] [--write]" >&2; exit 2 ;;
	esac
done

fields=(scope machines writes)

# Prints "<scope>: <problem>" for each reason <dir>'s readme.md isn't usable, or nothing.
# <readme> is the copy to check, so the caller can check and render the same snapshot.
scope_problems() {
	local dir=$1 readme=$2 name key why
	name=$(basename "$dir")
	if ! has_exact_file "$dir" readme.md; then
		printf '%s: no readme.md (the name is lowercase)\n' "$name"
		return
	fi
	for key in "${fields[@]}"; do
		why=$(frontmatter_problem "$readme" "$key")
		if [[ -n $why ]]; then
			printf '%s: readme.md %s\n' "$name" "$why"
			if [[ $why == "has no frontmatter" || $why == *"no closing ---" ]]; then return; fi
		fi
	done
}

# Prints the routing file, checking each scope in the same pass that renders it. A scope with
# problems is left out, and its problems are appended to <problems file>.
build() {
	local problems_file=$1
	cat <<'HEAD'
# Lore

Private knowledge for the agents on this machine: who the user is, how they work, and what they
know about each project. Read this first, then the readme of the scope repo you work in.

Each folder is its own private git repo, holding `projects/`, `skills/` and optionally `repos/`
and `agents.md`.

## Scopes on this machine

HEAD
	local found=no dir name readme why
	readme=$(mktemp)
	for dir in "$root"/*/; do
		dir=${dir%/}
		name=$(basename "$dir")
		# Check and render one snapshot, so an edit between the two can't slip through.
		: >"$readme"
		if has_exact_file "$dir" readme.md; then cp -- "$dir/readme.md" "$readme"; fi
		why=$(scope_problems "$dir" "$readme")
		if [[ -n $why ]]; then
			printf '%s\n' "$why" >>"$problems_file"
			continue
		fi
		found=yes
		printf -- '- **`%s/`**: %s\n' "$name" "$(frontmatter_value "$readme" scope)"
		printf '  - Cloned on: %s\n' "$(frontmatter_value "$readme" machines)"
		printf '  - Writes here: %s\n' "$(frontmatter_value "$readme" writes)"
		if [[ -f $root/$name/agents.md ]]; then
			printf '  - Read in every session: [%s/agents.md](%s/agents.md)\n' "$name" "$name"
		fi
	done
	rm -f -- "$readme"
	[[ $found == yes ]] || printf -- '- None yet.\n'
	cat <<'TAIL'

## Where writes go

- Into the scope whose "Writes here" fits. Read that repo's readme before writing.
- Unsure: the narrower scope. Moving content toward a broader scope can leak for good, while the
  reverse is safe to fix later.
- After writing, commit and push that repo.

## Code repos

Steering for contributing to a code repo that can't be checked into it sits in its scope's repo
at `repos/<code-repo>/`, with an upstream page `repos/<code-repo>.md` (its remote URL and local
path). Plans for it sit in a project under `projects/`. Lore is the only source: a checkout's
generated copy of its notes is never edited directly.

This file is generated by the lore skill's `routing.sh`; edit the scope readmes instead.
TAIL
}

# Render into a temporary file beside the routing file, so the old file is replaced in one
# rename, and only when every scope passed in this same pass.
problems_file=$(mktemp)
if [[ $write == yes ]]; then out=$(mktemp "$root/.readme.md.XXXXXX"); else out=$(mktemp); fi
trap 'rm -f -- "$problems_file" "$out"' EXIT
build "$problems_file" >"$out"

if [[ -s $problems_file ]]; then
	{
		cat "$problems_file"
		printf 'Each scope needs a readme.md whose frontmatter has scope, machines and writes,\n'
		printf 'each one plain line. %s/check.sh <repo> lists anything else it needs.\n' "$scripts"
	} >&2
	if [[ $write == yes ]]; then
		echo "routing.sh: not writing $root/readme.md until every scope is fixed" >&2
		exit 1
	fi
	echo "routing.sh: those scopes are left out below" >&2
fi
if [[ $write == yes ]]; then
	chmod 644 "$out"
	mv -f -- "$out" "$root/readme.md"
else
	cat "$out"
fi
